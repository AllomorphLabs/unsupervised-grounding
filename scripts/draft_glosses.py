"""Draft configs/glosses.yaml from configs/concepts.yaml using WordNet.

For each concept, takes the single-word lemmas of its chosen WordNet sense,
adds regular English inflections and the concept's hand-written extras, and
writes the result. Review the diff of glosses.yaml after running; fix
problems by editing concepts.yaml, never glosses.yaml.

Run by hand (needs the optional ``glosses`` dependency group):

    uv run --group glosses python scripts/draft_glosses.py

The first run downloads the lexicon:

    uv run --group glosses python -c "import wn; wn.download('omw-en:1.4')"
"""

from pathlib import Path

import wn
import yaml

LEXICON = "omw-en:1.4"
ROOT = Path(__file__).resolve().parent.parent
CONCEPTS = ROOT / "configs" / "concepts.yaml"
GLOSSES = ROOT / "configs" / "glosses.yaml"
VOWELS = set("aeiou")


def noun_forms(w: str) -> set[str]:
    if w.endswith(("s", "x", "z", "ch", "sh")):
        return {w, w + "es"}
    if w.endswith("y") and w[-2:-1] not in VOWELS:
        return {w, w[:-1] + "ies"}
    return {w, w + "s"}


def verb_forms(w: str) -> set[str]:
    forms = {w}
    # -s
    if w.endswith(("s", "x", "z", "ch", "sh", "o")):
        forms.add(w + "es")
    elif w.endswith("y") and w[-2:-1] not in VOWELS:
        forms.add(w[:-1] + "ies")
    else:
        forms.add(w + "s")
    # -ed / -ing, with e-dropping and consonant doubling for short CVC verbs
    if w.endswith("e"):
        forms |= {w + "d", w[:-1] + "ing"}
    elif (
        len(w) >= 3
        and w[-1] not in VOWELS | {"w", "x", "y"}
        and w[-2] in VOWELS
        and w[-3] not in VOWELS
    ):
        forms |= {w + w[-1] + "ed", w + w[-1] + "ing", w + "ed", w + "ing"}
    else:
        forms |= {w + "ed", w + "ing"}
    return forms


def expand(lemmas: list[str], pos: str) -> set[str]:
    forms: set[str] = set()
    for lemma in lemmas:
        w = lemma.lower()
        if not w.isalpha():  # skip multi-word and hyphenated lemmas
            continue
        forms |= noun_forms(w) if pos == "n" else verb_forms(w) if pos == "v" else {w}
    return forms


def main() -> None:
    en = wn.Wordnet(LEXICON)
    concepts = yaml.safe_load(CONCEPTS.read_text(encoding="utf-8"))
    out: dict[str, list[str]] = {}
    for group in concepts.values():
        for name, spec in group.items():
            synset = en.synset(spec["sense"])
            # Named individuals (people such as "Bush, George W. Bush", particular places) are
            # WordNet instances. Our concepts are ordinary words, so refuse them outright.
            if synset.get_related("instance_hypernym"):
                raise ValueError(f"{name}: sense {spec['sense']} is a named individual")
            forms = expand(synset.lemmas(), synset.pos)
            forms |= {name} | {w.lower() for w in spec.get("extra", [])}
            out[name] = sorted(forms)
    header = (
        "# Generated by scripts/draft_glosses.py from configs/concepts.yaml,\n"
        f"# using WordNet ({LEXICON}).\n"
        "# Do not edit by hand: change concepts.yaml and rerun the script.\n"
        "# Each invented word must be at least 3 edits from every gloss for its meaning.\n\n"
    )
    text = header + yaml.safe_dump(out, sort_keys=True, width=100)
    GLOSSES.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(out)} concepts to {GLOSSES.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
