"""The invented vocabulary, and the check that it doesn't resemble English.

Stems are random strings of the shape consonant-vowel-consonant-vowel-consonant
(CVCVC), so every stem has the same length and the same sound pattern;
interchangeable entities can't be told apart by the shape of their names.
Suffixes are random vowel-consonant pairs (VC).

The proposal's rule, applied to stems and to every inflected form a stem can
take (technical decision 7):

- A word for an action, object or place must be at least 3 edits from every
  English gloss for its meaning (``configs/glosses.yaml``).
- Every word, including agent names, must be at least 2 edits from each of the
  20,000 most common English words (``wordfreq``).

Grammatical suffixes aren't covered by the rule. A vocabulary is generated by
rejection sampling and checked again as a whole before it is returned, so no
vocabulary that fails the check can be used.
"""

from dataclasses import dataclass
from functools import cache
from pathlib import Path
from string import ascii_lowercase

import numpy as np
import wordfreq
import yaml

CONSONANTS = "bdfgklmnprstvz"
VOWELS = "aeiou"
COMMON_WORDS = 20_000
GLOSS_DISTANCE = 3  # minimum edits from each gloss for the word's meaning
COMMON_DISTANCE = 2  # minimum edits from each common English word
GLOSSES = Path(__file__).resolve().parents[4] / "configs" / "glosses.yaml"


@cache
def common_words(n: int = COMMON_WORDS) -> frozenset[str]:
    return frozenset(w.lower() for w in wordfreq.top_n_list("en", n))


@cache
def load_glosses(path: Path = GLOSSES) -> dict[str, tuple[str, ...]]:
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    return {k: tuple(v) for k, v in raw.items()}


def edits1(word: str) -> set[str]:
    """Every string one edit (delete, substitute, insert) away from ``word``."""
    splits = [(word[:i], word[i:]) for i in range(len(word) + 1)]
    deletes = {a + b[1:] for a, b in splits if b}
    subs = {a + c + b[1:] for a, b in splits if b for c in ascii_lowercase}
    inserts = {a + c + b for a, b in splits for c in ascii_lowercase}
    return deletes | subs | inserts


def edit_distance(a: str, b: str) -> int:
    """Levenshtein distance."""
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def problems_with(form: str, glosses: tuple[str, ...], common: frozenset[str]) -> list[str]:
    """Why ``form`` breaks the rule; empty if it passes."""
    out = []
    # COMMON_DISTANCE is 2, so "too close" means within one edit.
    near = ({form} | edits1(form)) & common
    if near:
        out.append(f"{form!r} is within 1 edit of common English {sorted(near)[:3]}")
    for g in glosses:
        if edit_distance(form, g) < GLOSS_DISTANCE:
            out.append(f"{form!r} is within {GLOSS_DISTANCE - 1} edits of its gloss {g!r}")
    return out


@dataclass(frozen=True)
class Vocab:
    """Stems for every concept, and suffixes for every grammatical role.

    ``stems`` maps a concept (an agent, object or place name from the world,
    or a verb) to its invented stem. ``suffixes`` maps a role to its suffix.
    ``inflections`` maps each concept to the suffix roles it can take.
    """

    stems: dict[str, str]
    suffixes: dict[str, str]
    inflections: dict[str, tuple[str, ...]]

    def forms(self, concept: str) -> list[str]:
        """The bare stem and every inflected form of ``concept``."""
        stem = self.stems[concept]
        return [stem] + [stem + self.suffixes[r] for r in self.inflections[concept]]


def check_vocab(
    vocab: Vocab,
    glosses: dict[str, tuple[str, ...]] | None = None,
    common: frozenset[str] | None = None,
) -> list[str]:
    """Every rule the vocabulary breaks; empty if it passes."""
    glosses = load_glosses() if glosses is None else glosses
    common = common_words() if common is None else common
    out = []
    for concept in vocab.stems:
        for form in vocab.forms(concept):
            out.extend(problems_with(form, glosses.get(concept, ()), common))
    stems = list(vocab.stems.values())
    if len(set(stems)) != len(stems):
        out.append("two concepts share a stem")
    if len(set(vocab.suffixes.values())) != len(vocab.suffixes):
        out.append("two roles share a suffix")
    all_forms = [f for c in vocab.stems for f in vocab.forms(c)]
    if len(set(all_forms)) != len(all_forms):
        out.append("two different words have the same written form")
    return out


def _random_stem(rng: np.random.Generator) -> str:
    c, v = CONSONANTS, VOWELS
    return "".join(
        (
            c[rng.integers(len(c))],
            v[rng.integers(len(v))],
            c[rng.integers(len(c))],
            v[rng.integers(len(v))],
            c[rng.integers(len(c))],
        )
    )


def _random_suffix(rng: np.random.Generator) -> str:
    return VOWELS[rng.integers(len(VOWELS))] + CONSONANTS[rng.integers(len(CONSONANTS))]


def generate_vocab(
    inflections: dict[str, tuple[str, ...]],
    roles: tuple[str, ...],
    rng: np.random.Generator,
    glosses: dict[str, tuple[str, ...]] | None = None,
    max_tries: int = 10_000,
) -> Vocab:
    """Draw a random vocabulary that passes the English-distance check.

    ``inflections`` maps each concept to the suffix roles it takes, and
    ``roles`` lists every suffix role. Concepts are drawn in the order given.
    """
    glosses = load_glosses() if glosses is None else glosses
    common = common_words()

    suffixes: dict[str, str] = {}
    for role in roles:
        while (s := _random_suffix(rng)) in suffixes.values():
            pass
        suffixes[role] = s

    stems: dict[str, str] = {}
    taken: set[str] = set()
    for concept, roles_taken in inflections.items():
        for _ in range(max_tries):
            stem = _random_stem(rng)
            forms = [stem] + [stem + suffixes[r] for r in roles_taken]
            if stem in stems.values() or taken & set(forms):
                continue
            if not any(problems_with(f, glosses.get(concept, ()), common) for f in forms):
                break
        else:
            raise RuntimeError(f"no acceptable stem for {concept!r} after {max_tries} tries")
        stems[concept] = stem
        taken |= set(forms)

    vocab = Vocab(stems, suffixes, dict(inflections))
    if problems := check_vocab(vocab, glosses, common):
        raise RuntimeError("generated vocabulary fails the check: " + "; ".join(problems))
    return vocab
